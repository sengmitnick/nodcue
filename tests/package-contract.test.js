import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import test from 'node:test';

const appRoot = fileURLToPath(new URL('../src/', import.meta.url));
const readmePath = fileURLToPath(new URL('../README.md', import.meta.url));
const serverConfigPath = fileURLToPath(new URL('../server/config.js', import.meta.url));
const glassesConfigExamplePath = fileURLToPath(new URL('../config/nod-service-config.example.js', import.meta.url));

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const resolved = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...await walk(resolved));
    } else {
      files.push(resolved);
    }
  }
  return files;
}

test('contains the required production surfaces', async () => {
  const files = (await walk(appRoot)).map((file) => path.relative(appRoot, file));
  for (const required of [
    'AGENTS.md',
    'app.js',
    'app.json',
    'lib/action-menu.js',
    'lib/pronunciation-session.js',
    'pages/index/index.ink',
    'assets/icons/speak.svg',
    'assets/icons/next.svg',
    'assets/icons/refresh.svg',
    'assets/icons/login.svg',
    'assets/icons/exit.svg',
  ]) {
    assert.ok(files.includes(required), `${required} is required`);
  }
  assert.equal(files.includes('VERSION'), false, 'VERSION is generated by aix pack');
  assert.equal(files.some((file) => file === '.env' || file.includes('node_modules')), false);
  assert.equal(files.some((file) => /^(server|tests|deliverables)\//.test(file)), false);
});

test('does not retain the source app camera, model, or storage behavior', async () => {
  const files = await walk(appRoot);
  const source = (await Promise.all(files.map((file) => readFile(file, 'utf8')))).join('\n');
  assert.match(source, /new Gyroscope/);
  assert.doesNotMatch(source, /LanguageModel|createCameraContext|env_english_/);
  assert.doesNotMatch(source, /api[_-]?key|authorization:\s*bearer/i);
});

test('documents the PostgreSQL and Dokploy production workflow', async () => {
  const readme = await readFile(readmePath, 'utf8');
  assert.match(readme, /npm test/);
  assert.match(readme, /npm start/);
  assert.match(readme, /npm run pack/);
  assert.match(readme, /src\/.*唯一|唯一.*src\//s);
  assert.match(readme, /PostgreSQL/);
  assert.match(readme, /Dokploy/);
  assert.match(readme, /config\/nod-service-config\.example\.js/);
  assert.doesNotMatch(readme, /adb reverse/);
  assert.doesNotMatch(readme, /ngrok http 3200/);
  assert.match(readme, /DEVICE_SERIAL/);
  assert.match(readme, /AIX_DEVICE_PATH/);
  assert.doesNotMatch(readme, /server\/data\/nod-pronouncer\.json/);
  assert.match(readme, /DATABASE_URL/);
  assert.match(readme, /NOD_CLIENT_KEY/);
  assert.match(readme, /NOD_SESSION_SECRET/);
});

test('keeps the server on 3200 and ships a matching local client configuration example', async () => {
  const [serverConfig, glassesConfig] = await Promise.all([
    readFile(serverConfigPath, 'utf8'),
    readFile(glassesConfigExamplePath, 'utf8'),
  ]);
  assert.match(serverConfig, /NOD_SERVER_PORT \|\| 3200/);
  assert.match(serverConfig, /DATABASE_URL/);
  assert.doesNotMatch(serverConfig, /NOD_DATA_FILE/);
  assert.match(glassesConfig, /http:\/\/127\.0\.0\.1:3200/);
  assert.match(glassesConfig, /nod-pronouncer-local-client/);
  assert.doesNotMatch(glassesConfig, /ngrok-free\.dev/);
  assert.doesNotMatch(`${serverConfig}\n${glassesConfig}`, /127\.0\.0\.1:31?00|NOD_SERVER_PORT \|\| 3100/);
});
